/**
 * The research IT and IRB sheet, generated from lab.toml and the studies in
 * the database, so what a reviewer signs matches what runs. Markdown, for
 * printing. docs/for-research-it-and-irb.md explains the rules; this sheet
 * says how this deployment sets them.
 *
 *   LabConfig + tool registry + agents now + studies   ->  renderSheet()   pure
 */

import { parseAgentDocument } from "./agent.ts";
import type { SharedCore } from "./boot-shared.ts";
import { ceilingOf, type Placement } from "./dataclass.ts";
import type { LabConfig } from "./config.ts";
import type { AgentVersionHash } from "./hash.ts";
import { activeFreezes, deviations, listStudies, type Deviation, type Freeze, type Study } from "./study.ts";
import type { ToolRegistry } from "./tools.ts";

export interface SheetInput {
  readonly config: LabConfig;
  readonly registry: ToolRegistry;
  readonly agents: readonly { readonly agentId: string; readonly name: string; readonly source: "published" | "lab.toml"; readonly endpointId: string; readonly modelId: string; readonly ceiling: string }[];
  readonly studies: readonly { readonly study: Study; readonly freezes: readonly Freeze[]; readonly deviations: readonly Deviation[] }[];
}

const short = (h: AgentVersionHash | string) => h.slice(0, 12);
const row = (cells: readonly (string | number)[]) => `| ${cells.map((c) => String(c).replace(/\|/g, "\\|")).join(" | ")} |`;
const table = (head: readonly string[], rows: readonly (readonly (string | number)[])[]) => [row(head), row(head.map(() => "---")), ...rows.map(row)].join("\n");
const upTo = (p: Placement, kind: "model" | "http" | "chat" | "store") => {
  const c = ceilingOf(kind, p);
  return c === "none" ? "nothing" : `up to ${c}`;
};

export function renderSheet(s: SheetInput): string {
  const c = s.config;
  const out: string[] = [];
  out.push(`# Aliquot deployment sheet${c.labName ? `: ${c.labName}` : ""}`);
  out.push("");
  out.push(`Generated by \`aliquot sheet\` from \`${c.path}\` and the study tables. The rules behind each line are in docs/for-research-it-and-irb.md. A destination may receive a class only up to the ceiling of its placement; R is ${c.policy.reviewConfidential === "lab-only" ? "allowed to lab placements only" : "refused everywhere"}.`);
  out.push("");
  out.push("## Surfaces");
  out.push("");
  out.push(table(["Surface", "Kind", "Placement", "Answers shown", "Identifies with"], c.surfaces.map((x) => [x.id, x.kind, x.placement, upTo(x.placement, "chat"), x.kind === "web" ? "nothing (no sign-in yet)" : `bearer token from $${x.tokenEnv}`])));
  out.push("");
  out.push("## Model endpoints");
  out.push("");
  out.push(table(["Endpoint", "Base URL", "Placement", "Receives"], c.endpoints.map((e) => [e.id, e.baseUrl, e.placement, upTo(e.placement, "model")])));
  if (c.agentBackends.length) {
    out.push("");
    out.push(table(["Agent backend", "CLI", "Placement", "Receives"], c.agentBackends.map((b) => [b.id, b.kind, b.placement, upTo(b.placement, "model")])));
  }
  out.push("");
  out.push("## Tool hosts");
  out.push("");
  const hosts = Object.entries(c.hosts);
  out.push(hosts.length ? table(["Host", "Placement", "Receives"], hosts.map(([h, p]) => [h, p, upTo(p, "http")])) : "No host is declared in lab.toml, so every tool host is public and receives D0 only.");
  out.push("");
  out.push(table(["Tool", "Spec hash", "Returns", "Effects", "Hosts"], s.registry.list().map((t) => [t.manifest.name, short(t.hash), t.manifest.reads, t.manifest.effects, t.manifest.egress.join(", ") || "none"])));
  out.push("");
  out.push("## Store and keys");
  out.push("");
  out.push(`- Payloads (every prompt, answer and tool body) are in Postgres, placement ${c.store.placement}, which receives ${upTo(c.store.placement, "store").replace("up to", "classes up to")}.`);
  const keys = Object.entries(c.store.keyEnvs).map(([id, env]) => `${id} from $${env}`).join(", ");
  out.push(`- Bodies are encrypted with AES-256-GCM under payload keys named by id (${keys}); new payloads go under ${c.store.current}. No key value is written to the database.`);
  const classKeys = Object.entries(c.store.classKeys);
  if (classKeys.length) out.push(`- Classes under their own key: ${classKeys.map(([cls, id]) => `${cls} under ${id}`).join(", ")}. A process not given that key cannot read those bodies.`);
  out.push("- Bodies are addressed by HMAC-SHA256 under the lab's address key, kept wrapped under each payload key, so a hash never changes when `aliquot keys rotate` and `aliquot keys reencrypt` move payloads to a new key.");
  out.push("- Run records and the audit stream are hash-chained and hold payload hashes and classes, not text.");
  out.push("");
  out.push("## Retention");
  out.push("");
  const days = (m: Readonly<Partial<Record<string, number>>>) => Object.entries(m).map(([cls, d]) => `${cls} ${d} days`).join(", ");
  const { purgeDays, keepMinDays } = c.retention;
  out.push(
    Object.keys(purgeDays).length
      ? `- [policy.retention] redacts a run's bodies after the last run that names them: ${days(purgeDays)}. \`aliquot retention --apply\` does it when someone or a timer runs it; other classes are kept.`
      : "- [policy.retention] sets no purge window, so every body is kept.",
  );
  if (Object.keys(keepMinDays).length) out.push(`- Floors no body is redacted under: ${days(keepMinDays)}.`);
  out.push("- A redaction keeps the hash and a tombstone, so records still verify.");
  out.push("");
  out.push("## Detection");
  out.push("");
  out.push(`- ${c.participantIdPatterns.length} participant id pattern${c.participantIdPatterns.length === 1 ? "" : "s"} from lab.toml, on top of the built-in detectors. Text no pattern matches keeps its declared class.`);
  const floors = Object.entries(c.channelFloors);
  if (floors.length) out.push(`- Channel floors: ${floors.map(([ch, f]) => `${ch} ${f}`).join(", ")}.`);
  out.push("");
  out.push("## Agents");
  out.push("");
  out.push(s.agents.length ? table(["Agent", "Name", "From", "Model", "Ceiling"], s.agents.map((a) => [a.agentId, a.name, a.source, `${a.modelId} on ${a.endpointId}`, a.ceiling])) : "No agent is published or listed in lab.toml.");
  out.push("");
  out.push("## Studies");
  out.push("");
  if (!s.studies.length) out.push("No study is registered. A channel in no study runs whatever agent is published for it.");
  for (const { study, freezes, deviations } of s.studies) {
    out.push(`### ${study.id}: ${study.title}`);
    out.push("");
    out.push(`- Owner ${study.owner}, data floor ${study.dataFloor}${study.irbProtocol ? `, IRB protocol ${study.irbProtocol}` : ""}${study.preregUrl ? `, pre-registered at ${study.preregUrl}` : ""}.`);
    out.push(`- Channels: ${study.channels.map((ch) => `${ch.surface}:${ch.channelId}`).join(", ") || "none"}. A study channel runs its frozen version and is never routed.`);
    for (const f of freezes) out.push(`- Frozen: ${f.agentId} at version ${f.hash}, by ${f.frozenBy} on ${f.at.slice(0, 10)}. ${f.note}`);
    if (!freezes.length) out.push("- Nothing is frozen: its channels refuse every message.");
    for (const d of deviations) out.push(`- Protocol deviation: ${d.agentId} at ${short(d.hash)}, frozen by ${d.frozenBy} on ${d.frozenAt.slice(0, 10)}, unfrozen by ${d.by} on ${d.at.slice(0, 10)}. ${d.reason}`);
    out.push("");
  }
  return `${out.join("\n").trimEnd()}\n`;
}

/** The sheet for a booted deployment: its lab.toml, the agents it serves now, and every study with its freezes. */
export async function labSheet(core: Pick<SharedCore, "db" | "config" | "registry" | "agents">): Promise<string> {
  const heads = await core.db.query<{ document: unknown }>("select document from agent_heads order by agent_id");
  const published = heads.rows.map((r) => parseAgentDocument(r.document)).flatMap((p) => (p.ok ? [p.doc] : []));
  const docs = [...published.map((d) => ({ d, source: "published" as const })), ...core.agents.filter((a) => !published.some((p) => p.agentId === a.agentId)).map((d) => ({ d, source: "lab.toml" as const }))];
  const studies = await Promise.all((await listStudies(core.db)).map(async (study) => ({ study, freezes: await activeFreezes(core.db, study.id), deviations: await deviations(core.db, study.id) })));
  return renderSheet({
    config: core.config,
    registry: core.registry,
    agents: docs.map(({ d, source }) => ({ agentId: d.agentId, name: d.name, source, endpointId: d.model.endpointId, modelId: d.model.modelId, ceiling: d.ceiling })),
    studies,
  });
}
