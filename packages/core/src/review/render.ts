/**
 * The review pack as Markdown: one file per framework and a summary that lists what is not met first. Pure, and
 * deterministic for one lab.toml, so a committed pack can be compared with a fresh one.
 */

import { assessAll, FRAMEWORK_NAMES, FRAMEWORKS, STATUSES, type Framework, type ReviewConfig, type Row, type Status } from "./controls.ts";

export interface PackSource {
  /** The lab.toml path as the reader should see it, relative to the repository. */
  readonly configPath: string;
  readonly configSha256: string;
}

export const PACK_FILES: Readonly<Record<Framework, string>> = { hipaa: "hipaa.md", "800-171r3": "nist-800-171.md", hecvat: "hecvat-answers.md" };

const STATUS_WORDS: Readonly<Record<Status, string>> = { met: "met", partly: "partly", "not-met": "not met", "lab-responsibility": "lab's responsibility" };

const SCOPE =
  "Each row says what Aliquot does toward a control, and what this lab.toml makes true for it. It is not a statement that a deployment is compliant: that judgement is the institution's. A row reads met only when tests in the suite prove the mechanism, and the tests are named on the row.";

function cell(text: string): string {
  return text.replaceAll("|", "\\|").replaceAll("\n", " ");
}

function header(title: string, src: PackSource): string {
  return `# ${title}\n\nGenerated by \`pnpm review-pack --config ${src.configPath}\` from that file (sha256 \`${src.configSha256.slice(0, 16)}\`). Do not edit by hand; rerun the command.\n\n${SCOPE}\n`;
}

function frameworkFile(fw: Framework, rows: readonly Row[], src: PackSource): string {
  const body = rows
    .filter((r) => r.control.framework === fw)
    .map(({ control: c, assessment: a }) => {
      const tests = c.tests.length ? c.tests.map((t) => `\`${t}\``).join("<br>") : "none";
      return `| ${cell(c.id)} | ${cell(c.title)} | **${STATUS_WORDS[a.status]}** | ${cell(c.does)} | ${cell(a.why)} | ${cell(tests)} |`;
    });
  return [
    header(FRAMEWORK_NAMES[fw], src),
    "| Control | Area | Status | What Aliquot does toward it | This lab.toml | Tests |",
    "|---|---|---|---|---|---|",
    ...body,
    "",
  ].join("\n");
}

function summaryFile(rows: readonly Row[], src: PackSource): string {
  const count = (fw: Framework, s: Status) => rows.filter((r) => r.control.framework === fw && r.assessment.status === s).length;
  const notMet = rows.filter((r) => r.assessment.status === "not-met");
  return [
    header("Security review summary", src),
    `## Not met (${notMet.length})`,
    "",
    ...(notMet.length ? notMet.map(({ control: c, assessment: a }) => `- **${c.id}** ${c.title}: ${a.why} ([${PACK_FILES[c.framework]}](${PACK_FILES[c.framework]}))`) : ["None."]),
    "",
    "## Counts",
    "",
    `| Framework | ${STATUSES.map((s) => STATUS_WORDS[s]).join(" | ")} |`,
    `|---|${STATUSES.map(() => "---").join("|")}|`,
    ...FRAMEWORKS.map((fw) => `| [${FRAMEWORK_NAMES[fw]}](${PACK_FILES[fw]}) | ${STATUSES.map((s) => count(fw, s)).join(" | ")} |`),
    "",
    "Partly and lab's responsibility rows say, on each row, which part is Aliquot's and which is the lab's.",
    "",
  ].join("\n");
}

/** File name to contents, for the folder docs/review/<lab>/. */
export function renderPack(config: ReviewConfig, src: PackSource): Readonly<Record<string, string>> {
  const rows = assessAll(config);
  return {
    "summary.md": summaryFile(rows, src),
    ...Object.fromEntries(FRAMEWORKS.map((fw) => [PACK_FILES[fw], frameworkFile(fw, rows, src)])),
  };
}

/** The folder name under docs/review: the lab's name, else the folder lab.toml sits in. */
export function packSlug(config: ReviewConfig, fallback: string): string {
  const slug = (config.labName ?? fallback).toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
  return slug || "lab";
}
